import * as Schema from "effect/Schema"
import * as Models from "../../models.ts"

export const Charge = Schema.Struct({
  amount: Schema.Number,
  amount_captured: Schema.Number,
  amount_refunded: Schema.Number,
  application: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Application => Models.Application))),
  application_fee: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.ApplicationFee => Models.ApplicationFee))),
  application_fee_amount: Schema.NullOr(Schema.Number),
  authorization_code: Schema.optional(Schema.String),
  balance_transaction: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.BalanceTransaction => Models.BalanceTransaction))),
  billing_details: Schema.suspend((): typeof Models.BillingDetails => Models.BillingDetails),
  calculated_statement_descriptor: Schema.NullOr(Schema.String),
  captured: Schema.Boolean,
  created: Schema.Number,
  currency: Schema.String,
  customer: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Customer => Models.Customer), Schema.suspend((): typeof Models.DeletedCustomer => Models.DeletedCustomer))),
  description: Schema.NullOr(Schema.String),
  disputed: Schema.Boolean,
  failure_balance_transaction: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.BalanceTransaction => Models.BalanceTransaction))),
  failure_code: Schema.NullOr(Schema.String),
  failure_message: Schema.NullOr(Schema.String),
  fraud_details: Schema.NullOr(Schema.suspend((): typeof Models.ChargeFraudDetails => Models.ChargeFraudDetails)),
  id: Schema.String,
  level3: Schema.optional(Schema.suspend((): typeof Models.Level3 => Models.Level3)),
  livemode: Schema.Boolean,
  metadata: Schema.Record({ key: Schema.String, value: Schema.String }),
  object: Schema.Literal("charge"),
  on_behalf_of: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Account => Models.Account))),
  outcome: Schema.NullOr(Schema.suspend((): typeof Models.ChargeOutcome => Models.ChargeOutcome)),
  paid: Schema.Boolean,
  payment_intent: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.PaymentIntent => Models.PaymentIntent))),
  payment_method: Schema.NullOr(Schema.String),
  payment_method_details: Schema.NullOr(Schema.suspend((): typeof Models.PaymentMethodDetails => Models.PaymentMethodDetails)),
  presentment_details: Schema.optional(Schema.suspend((): typeof Models.PaymentFlowsPaymentIntentPresentmentDetails => Models.PaymentFlowsPaymentIntentPresentmentDetails)),
  radar_options: Schema.optional(Schema.suspend((): typeof Models.RadarRadarOptions => Models.RadarRadarOptions)),
  receipt_email: Schema.NullOr(Schema.String),
  receipt_number: Schema.NullOr(Schema.String),
  receipt_url: Schema.NullOr(Schema.String),
  refunded: Schema.Boolean,
  refunds: Schema.optional(Schema.NullOr(Schema.Struct({
  data: Schema.Array(Schema.suspend((): typeof Models.Refund => Models.Refund)),
  has_more: Schema.Boolean,
  object: Schema.Literal("list"),
  url: Schema.String,
}))),
  review: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Review => Models.Review))),
  shipping: Schema.NullOr(Schema.suspend((): typeof Models.Shipping => Models.Shipping)),
  source: Schema.NullOr(Schema.suspend((): typeof Models.PaymentSource => Models.PaymentSource)),
  source_transfer: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Transfer => Models.Transfer))),
  statement_descriptor: Schema.NullOr(Schema.String),
  statement_descriptor_suffix: Schema.NullOr(Schema.String),
  status: Schema.Literal("failed", "pending", "succeeded"),
  transfer: Schema.optional(Schema.Union(Schema.String, Schema.suspend((): typeof Models.Transfer => Models.Transfer))),
  transfer_data: Schema.NullOr(Schema.suspend((): typeof Models.ChargeTransferData => Models.ChargeTransferData)),
  transfer_group: Schema.NullOr(Schema.String),
})
export type Charge = typeof Charge.Type
