import * as Schema from "effect/Schema"
import * as Models from "../../models.ts"

export const CreditNote = Schema.Struct({
  amount: Schema.Number,
  amount_shipping: Schema.Number,
  created: Schema.Number,
  currency: Schema.String,
  customer: Schema.Union(Schema.String, Schema.suspend((): typeof Models.Customer => Models.Customer), Schema.suspend((): typeof Models.DeletedCustomer => Models.DeletedCustomer)),
  customer_account: Schema.NullOr(Schema.String),
  customer_balance_transaction: Schema.NullOr(Schema.Union(Schema.String, Schema.suspend((): typeof Models.CustomerBalanceTransaction => Models.CustomerBalanceTransaction))),
  discount_amount: Schema.Number,
  discount_amounts: Schema.Array(Schema.suspend((): typeof Models.DiscountsResourceDiscountAmount => Models.DiscountsResourceDiscountAmount)),
  effective_at: Schema.NullOr(Schema.Number),
  id: Schema.String,
  invoice: Schema.Union(Schema.String, Schema.suspend((): typeof Models.Invoice => Models.Invoice)),
  lines: Schema.Struct({
  data: Schema.Array(Schema.suspend((): typeof Models.CreditNoteLineItem => Models.CreditNoteLineItem)),
  has_more: Schema.Boolean,
  object: Schema.Literal("list"),
  url: Schema.String,
}),
  livemode: Schema.Boolean,
  memo: Schema.NullOr(Schema.String),
  metadata: Schema.NullOr(Schema.Record({ key: Schema.String, value: Schema.String })),
  number: Schema.String,
  object: Schema.Literal("credit_note"),
  out_of_band_amount: Schema.NullOr(Schema.Number),
  pdf: Schema.String,
  post_payment_amount: Schema.Number,
  pre_payment_amount: Schema.Number,
  pretax_credit_amounts: Schema.Array(Schema.suspend((): typeof Models.CreditNotesPretaxCreditAmount => Models.CreditNotesPretaxCreditAmount)),
  reason: Schema.NullOr(Schema.Literal("duplicate", "fraudulent", "order_change", "product_unsatisfactory")),
  refunds: Schema.Array(Schema.suspend((): typeof Models.CreditNoteRefund => Models.CreditNoteRefund)),
  shipping_cost: Schema.NullOr(Schema.suspend((): typeof Models.InvoicesResourceShippingCost => Models.InvoicesResourceShippingCost)),
  status: Schema.Literal("issued", "void"),
  subtotal: Schema.Number,
  subtotal_excluding_tax: Schema.NullOr(Schema.Number),
  total: Schema.Number,
  total_excluding_tax: Schema.NullOr(Schema.Number),
  total_taxes: Schema.NullOr(Schema.Array(Schema.suspend((): typeof Models.BillingBillResourceInvoicingTaxesTax => Models.BillingBillResourceInvoicingTaxesTax))),
  type: Schema.Literal("mixed", "post_payment", "pre_payment"),
  voided_at: Schema.NullOr(Schema.Number),
})
export type CreditNote = typeof CreditNote.Type
