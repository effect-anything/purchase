import * as Schema from "effect/Schema"
import * as Models from "../../models.ts"

export const Order = Schema.Struct({
  id: Schema.String,
  created_at: Schema.String,
  modified_at: Schema.NullOr(Schema.String),
  status: Schema.suspend((): typeof Models.OrderStatus => Models.OrderStatus),
  paid: Schema.Boolean,
  subtotal_amount: Schema.Number,
  discount_amount: Schema.Number,
  net_amount: Schema.Number,
  tax_amount: Schema.Number,
  total_amount: Schema.Number,
  applied_balance_amount: Schema.Number,
  due_amount: Schema.Number,
  refunded_amount: Schema.Number,
  refunded_tax_amount: Schema.Number,
  currency: Schema.String,
  billing_reason: Schema.suspend((): typeof Models.OrderBillingReason => Models.OrderBillingReason),
  billing_name: Schema.NullOr(Schema.String),
  billing_address: Schema.NullOr(Schema.suspend((): typeof Models.Address => Models.Address)),
  invoice_number: Schema.String,
  is_invoice_generated: Schema.Boolean,
  receipt_number: Schema.NullOr(Schema.String),
  seats: Schema.optional(Schema.NullOr(Schema.Number)),
  customer_id: Schema.String,
  product_id: Schema.NullOr(Schema.String),
  discount_id: Schema.NullOr(Schema.String),
  subscription_id: Schema.NullOr(Schema.String),
  checkout_id: Schema.NullOr(Schema.String),
  metadata: Schema.suspend((): typeof Models.MetadataOutputType => Models.MetadataOutputType),
  custom_field_data: Schema.optional(Schema.Record({ key: Schema.String, value: Schema.NullOr(Schema.Union(Schema.String, Schema.Number, Schema.Boolean, Schema.String)) })),
  platform_fee_amount: Schema.Number,
  platform_fee_currency: Schema.NullOr(Schema.String),
  customer: Schema.suspend((): typeof Models.OrderCustomer => Models.OrderCustomer),
  product: Schema.NullOr(Schema.suspend((): typeof Models.OrderProduct => Models.OrderProduct)),
  discount: Schema.NullOr(Schema.Union(Schema.suspend((): typeof Models.DiscountFixedOnceForeverDurationBase => Models.DiscountFixedOnceForeverDurationBase), Schema.suspend((): typeof Models.DiscountFixedRepeatDurationBase => Models.DiscountFixedRepeatDurationBase), Schema.suspend((): typeof Models.DiscountPercentageOnceForeverDurationBase => Models.DiscountPercentageOnceForeverDurationBase), Schema.suspend((): typeof Models.DiscountPercentageRepeatDurationBase => Models.DiscountPercentageRepeatDurationBase))),
  subscription: Schema.NullOr(Schema.suspend((): typeof Models.OrderSubscription => Models.OrderSubscription)),
  items: Schema.Array(Schema.suspend((): typeof Models.OrderItemSchema => Models.OrderItemSchema)),
  description: Schema.String,
  refundable_amount: Schema.Number,
  refundable_tax_amount: Schema.Number,
})
export type Order = typeof Order.Type
